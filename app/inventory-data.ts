export function inventoryTotal(quantities: Record<string, number>) {
  return inventoryItems.reduce((sum, entry) => {
    const qty = quantities[entry.item] ?? 0;
    if (!Number.isSafeInteger(qty) || qty < 0 || qty > 999) throw new Error("Invalid inventory quantity");
    return sum + Math.round(entry.volumeM3 * 100) * qty;
  }, 0) / 100;
}
